    private void tambahBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_tambahBtnActionPerformed
        if (!nisTxt.getText().matches("\\d+")) {
            JOptionPane.showMessageDialog(null, "NIS hanya boleh berisi angka!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        String jenis = null;
        if (lakiLakiRb.isSelected()) {
            jenis = "Laki-Laki";
        } else if (perempuanRb.isSelected()) {
            jenis = "Perempuan";
        } else {
            JOptionPane.showMessageDialog(null, "Pilih jenis kelamin!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (alamatTxtArea.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Alamat tidak boleh kosong!", "Validasi", JOptionPane.WARNING_MESSAGE);
            alamatTxtArea.requestFocus();
            return;
        }

        if (tanggalLahirDc.getDate() == null) {
            JOptionPane.showMessageDialog(null, "Tanggal lahir tidak boleh kosong!", "Peringatan", JOptionPane.WARNING_MESSAGE);
            return;
        }
        String sql = "INSERT INTO siswa (nis, nama_lengkap, jenis_kelamin, alamat, tanggal_lahir) VALUES (?,?,?,?,?)";

        try (Connection conn = koneksi.getConnection();
             PreparedStatement stat = conn.prepareStatement(sql)) {

            stat.setString(1, nisTxt.getText());
            stat.setString(2, namaTxt.getText());
            stat.setString(3, jenis);
            stat.setString(4, alamatTxtArea.getText());
            java.sql.Date sqlDate = new java.sql.Date(tanggalLahirDc.getDate().getTime());
            stat.setDate(5, sqlDate);

            stat.executeUpdate();
            JOptionPane.showMessageDialog(null, "Data berhasil disimpan");
            nisTxt.requestFocus();

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(null, "Data gagal disimpan: " + e.getMessage());
            e.printStackTrace();
        }
    }//GEN-LAST:event_tambahBtnActionPerformed

    private void cariBtnActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cariBtnActionPerformed
        String nama = cariTxt.getText(); 
        DefaultTableModel model = new DefaultTableModel();
        model.addColumn("ID");
        model.addColumn("NIS");
        model.addColumn("Nama");
        model.addColumn("Jenis Kelamin");
        model.addColumn("Tanggal Lahir");
        model.addColumn("Alamat");
        model.addColumn("id_kelas");

        try {
            Connection conn = koneksi.getConnection();
            String sql = "SELECT * FROM siswa  WHERE LOWER(nama_lengkap) LIKE ?";
            PreparedStatement stmt = conn.prepareStatement(sql);
            stmt.setString(1, "%" + nama.toLowerCase() + "%");

            ResultSet rs = stmt.executeQuery();

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getInt("id_siswa"),
                    rs.getString("nis"),
                    rs.getString("nama_lengkap"),
                    rs.getString("tanggal_lahir"),
                    rs.getString("jenis_kelamin"),
                    rs.getString("alamat"),
                    rs.getString("id_kelas")
                });
            }

            guruTbl.setModel(model);
        } catch (SQLException ex) {
            JOptionPane.showMessageDialog(this, "Error: " + ex.getMessage());
        }
    }//GEN-LAST:event_cariBtnActionPerformed

