    private void isiComboNamaSiswa() {
        try {
            String url = "jdbc:mysql://localhost:3306/db_sekolah";
            String user = "root";
            String password = "";

            Connection conn = DriverManager.getConnection(url, user, password);
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery("SELECT nama_kelas FROM kelas");
                    
            while (rs.next()) {
                String namaKelas = rs.getString("nama_kelas");
                kelasDd.addItem(namaKelas);
//                System.out.println("Memuat: " + namaKelas);
            }

            rs.close();
            st.close();
            conn.close();

        } catch (Exception e) {
            e.printStackTrace();
          JOptionPane.showMessageDialog(this, "Gagal load kelas: " + e.toString());
        }   
    }
    
     
